// Load local.properties (gitignored). project.findProperty() does NOT read this file
// by default — only gradle.properties + -P flags + env. Reading it manually so the
// developer can keep secrets like GOOGLE_WEB_CLIENT_ID out of source control.
val localProps = Properties().apply {
    val f = rootProject.file("local.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

fun resolveProp(key: String): String =
    localProps.getProperty(key)
        ?: (project.findProperty(key) as String?)
        ?: System.getenv(key)
        ?: ""

